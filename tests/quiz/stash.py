#
# 15. Внесите любые изменения в ваш репозиторий и сохраните второй стэш под именем "SENATOROV ver2"
#
# Ответ: После внесения изменений выполнить git stash push -m "SENATOROV ver2".
# Команда git stash list подтверждает, что стэш создан.
#
# ![Creating the second stash](images/stash-second-and-apply.png)
