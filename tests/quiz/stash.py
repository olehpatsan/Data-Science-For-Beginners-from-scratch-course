"""Stash questions."""

# 1. Что делает команда git stash?
#
# Ответ: Сохраняет незакоммиченные изменения рабочей директории и индекса во
# временный список (stash), возвращая рабочее дерево к состоянию HEAD.
#
# 2. Как просмотреть список всех сохранённых изменений (стэшей)?
#
# Ответ: Выполнить git stash list. В VS Code список стэшей можно увидеть в
# панели Source Control, в разделе Stashes.
#
# 3. Какая команда применяется для использования верхнего стэша?
#
# Ответ: git stash apply.
#
# 4. Как применить конкретный стэш по его номеру?
#
# Ответ: git stash apply stash@{номер}
#
# 5. Чем отличается команда git stash apply от git stash pop?
#
# Ответ: apply применяет выбранный стэш и оставляет его в списке. pop применяет
# стэш и удаляет его из списка после успешного применения.
#
# 6. Что делает команда git stash drop?
#
# Ответ: git stash drop удаляет указанный стэш (по умолчанию верхний) без
# применения изменений.
#
# 7. Как полностью очистить все сохранённые стэши?
#
# Ответ: git stash clear
#
# 8. В каких случаях удобно использовать git stash?
#
# Ответ: Когда нужно временно отложить незавершённые изменения, например перед
# переключением ветки, обновлением ветки или срочной правкой другой задачи.
#
# 9. Что произойдёт, если выполнить git stash pop, но в проекте есть конфликтующие изменения?
#
# Ответ: Git попробует применить изменения и остановится при конфликте. Нужно
# разрешить конфликт, добавить исправленные файлы в индекс и завершить работу;
# стэш при конфликте обычно остаётся в списке.
#
# 10. Можно ли восстановить удалённый стэш после выполнения git stash drop?
#
# Ответ: Иногда можно найти объект через git reflog или git fsck, пока Git не
# удалил его сборкой мусора. Гарантии восстановления нет, поэтому важный стэш
# лучше не удалять.
#
# 11. Что делает команда git stash save "NAME_STASH"
#
# Ответ: Сохраняет изменения в стэш с сообщением NAME_STASH, но команда
# устарела. Рекомендуемый вариант: git stash push -m "NAME_STASH".
#
# 12. Что делает команда git stash apply "NUMBER_STASH"
#
# Ответ: Применяет изменения из выбранного стэша и оставляет его в списке,
# например: git stash apply stash@{0}.
#
# 13. Что делает команда git stash pop "NUMBER_STASH"
#
# Ответ: Применяет выбранный стэш и при успехе удаляет его из списка, например:
# git stash pop stash@{0}.
#
# 14. Сохраните текущие изменения в стэш под названием "SENATOROV ver1", вставьте скриншот из терминала
#
# Ответ: git stash push -m "SENATOROV ver1"
#
